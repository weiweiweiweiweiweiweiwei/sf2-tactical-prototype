"""SF2 relative damage → the marked block in src/01_core.js (SF2_DAMAGE, applied onto WEAPON_DATABASE after SF2_WEAPONS).
Every gun with an SF2 class (tools/sf2_weapon_table.py GUNS) takes SF2's own InstantHitDamage / InstantHitDamageMin and its
falloff range (WeaponRangeDamageMax → Min, 1 m = 39.37 units), scaled by its weapon type's factor K: the median of
(our damageNear / SF2 damage) over that type, taken once from the v65 table (decision D14) and fixed here, so each class keeps its
time to kill and the guns inside it keep SF2's order. Shotguns keep their own numbers (see K).
  python tools/sf2_damage_table.py
"""
import json, re

CORE = 'src/01_core.js'
K = {'assault': 0.754, 'smg': 0.774, 'lmg': 0.839, 'sniper': 0.743, 'pistol': 0.938}  # (v66c2 medians; shotguns left out: SF2's pellet count is not in the data, and its longer range made every pump gun a one-shot at 15 m)
U = 39.37


def guns():
    s = open('tools/sf2_weapon_table.py', encoding='utf-8').read()
    body = re.search(r"GUNS = \{(.*?)\n\}", s, re.S).group(1)
    return re.findall(r"^\s*'([a-z0-9_]+)':\s*\('([A-Za-z0-9_]+)'", body, re.M)


def types():
    src = open(CORE, encoding='utf-8').read()
    db = src[src.index('const WEAPON_DATABASE'):src.index('// <sf2-weapons>')]
    return dict(re.findall(r"^  ([a-z0-9_]+): \{[^\n]*\n?(?:[^\n]*\n){0,4}?[^\n]*type: '([a-z]+)'", db, re.M))


def main():
    W = json.load(open('docs/research/sf2/client-data/weapons.json', encoding='utf-8'))
    T = types()
    rows = []
    for gid, cls in guns():
        w, t = W.get('SFCWeapon' + cls), T.get(gid)
        if not w or not t or t not in K or not w.get('InstantHitDamage'):
            continue
        k = K[t]
        near = w['InstantHitDamage'][0]; far = w.get('InstantHitDamageMin', near)
        a = w.get('WeaponRangeDamageMax', 1e6) / U; b = w.get('WeaponRangeDamageMin', a * U + U) / U
        o = [round(near * k, 1), round(far * k, 1), round(a, 1), round(max(b, a + 1), 1)]
        rows.append(f"  {gid}: {json.dumps(o)}, // SFCWeapon{cls} {near:g} → {far:g}")
    block = ('// <sf2-damage>\n'
             '/* v66c2 SF2\'s own damage order (decision D14) — generated by tools/sf2_damage_table.py from docs/research/sf2/client-data/weapons.json:\n'
             '   [damageNear, damageFar, falloffStart m, falloffEnd m] = SF2\'s InstantHitDamage / Min and range × the type\'s factor (sf2_damage_table.K). */\n'
             'const SF2_DAMAGE = {\n' + '\n'.join(rows) + '\n};\n'
             'for (const [id, [n, f, a, b]] of Object.entries(SF2_DAMAGE)) Object.assign(WEAPON_DATABASE[id], { damageNear: n, damageFar: f, falloffStart: a, falloffEnd: b });\n'
             '// </sf2-damage>')
    src = open(CORE, encoding='utf-8').read()
    if '// <sf2-damage>' in src:
        src = re.sub(r'// <sf2-damage>.*?// </sf2-damage>', lambda m: block, src, flags=re.S)
    else:
        src = src.replace('// </sf2-weapons>\n', '// </sf2-weapons>\n' + block + '\n', 1)
    open(CORE, 'w', encoding='utf-8').write(src)
    print(f'{CORE}: {len(rows)} guns')


if __name__ == '__main__':
    main()
