"""Apex damage table → the marked block in src/01_core.js (APEX_WEAPONS + APEX_POOL), from docs/research/apex/weapons-full.json
('current' layer: official > S30.1 > S14). In the Apex damage model each of our guns takes the per-shot damage, head / leg
multipliers and headshot range of an Apex counterpart: the gun of the same class whose rate of fire (rechamber included) is
nearest in log scale (apexFor in 01_core.js), so the damage per second stays near Apex's.
  python tools/apex_weapon_table.py
Burst, charge, beam, ramp-up and overheat guns (Hemlok, Nemesis, Prowler, Charge Rifle, Triple Take, Bocek, Devotion, L-STAR) are in
the table but in no pool: none of our guns fires that way.
"""
import json, re

JSON = 'docs/research/apex/weapons-full.json'
CORE = 'src/01_core.js'
IDS = {  # Apex name → our id
    'HAVOC Rifle': 'havoc', 'Hemlok Burst AR': 'hemlok', 'Nemesis Burst AR': 'nemesis', 'R-301 Carbine': 'r301', 'VK-47 Flatline': 'flatline',
    'Alternator SMG': 'alternator', 'C.A.R. SMG': 'car', 'Prowler Burst PDW': 'prowler', 'R-99 SMG': 'r99', 'Volt SMG': 'volt',
    'Devotion LMG': 'devotion', 'L-STAR EMG': 'lstar', 'M600 Spitfire': 'spitfire', 'Rampage LMG': 'rampage', '30-30 Repeater': 'r3030',
    'Bocek Compound Bow': 'bocek', 'G7 Scout': 'g7', 'Triple Take': 'tripletake', 'Charge Rifle': 'chargerifle', 'Kraber .50-Cal Sniper': 'kraber',
    'Longbow DMR': 'longbow', 'Sentinel': 'sentinel', 'EVA-8 Auto': 'eva8', 'Mastiff Shotgun': 'mastiff', 'Mozambique Shotgun': 'mozambique',
    'Peacekeeper': 'peacekeeper', 'P2020': 'p2020', 'RE-45 Auto': 're45', 'Wingman': 'wingman',
}
POOL = {  # our weapon type → the Apex guns it can map to
    'assault': ['r301', 'flatline', 'havoc'], 'smg': ['alternator', 'car', 'r99', 'volt'], 'lmg': ['spitfire', 'rampage'],
    'pistol': ['p2020', 're45', 'wingman'], 'shotgun': ['eva8', 'mastiff', 'peacekeeper', 'mozambique'],
    'sniper': ['longbow', 'g7', 'r3030'], 'sniper_bolt': ['kraber', 'sentinel'],  # bolt actions (def.bolt) only to Apex's bolt guns
}


def main():
    guns = json.load(open(JSON, encoding='utf-8'))['weapons']
    rows = []
    for g in guns:
        c = g['current']
        rpm = c['rpm'] if not c.get('rechamber_s') else 60 / (60 / c['rpm'] + c['rechamber_s'])  # one shot's full cycle
        o = {'name': g['name'], 'body': c['body'], 'head': c['head'], 'leg': c['leg'], 'pellets': c.get('pellets') or 1,
             'rpm': round(rpm, 1), 'headMax': c.get('headshot_max_m') or 1e6}
        rows.append(f"  {IDS[g['name']]}: {json.dumps(o, ensure_ascii=False, separators=(', ', ': '))},")
    block = ('// <apex-weapons>\n'
             '/* v62u Apex damage per gun (docs/research/apex/weapons-full.json \'current\': official > S30.1 > S14) — generated by\n'
             '   tools/apex_weapon_table.py. body / head / leg per pellet, rpm with the rechamber, headMax = headshot range (m). */\n'
             'const APEX_WEAPONS = {\n' + '\n'.join(rows) + '\n};\n'
             'const APEX_POOL = ' + json.dumps(POOL, separators=(', ', ': ')) + ';\n'
             '// </apex-weapons>')
    src = open(CORE, encoding='utf-8').read()
    src, n = re.subn(r'// <apex-weapons>.*?// </apex-weapons>', lambda m: block, src, flags=re.S)
    if not n: raise SystemExit('no <apex-weapons> block in ' + CORE)
    open(CORE, 'w', encoding='utf-8').write(src)
    print(f'{CORE}: {len(rows)} Apex guns')


if __name__ == '__main__':
    main()
